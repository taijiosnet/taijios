#!/usr/bin/env python3
"""Check that lib/preinstall.list drives the catalog.

Run against a tree generated by:
  python3 tools/generate-app-catalog.py --preinstall lib/preinstall.list \
      --output-root <dir>

Checks, in order:
  1. every row whose bundle exists in the output root has an entry whose Exec
     and TryExec name that bundle
  2. every row whose bundle is absent in the output root has no entry
  3. desktop ids are stable across two runs and the second run is byte-identical
  4. a row naming a missing bundle emits nothing
  5. --preinstall leaves the catalog entries it did not write untouched

Usage: catalog_preinstall_test.py <output-root> [--manifest PATH]
"""
import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MANIFEST = ROOT / 'lib/preinstall.list'
GENERATOR = ROOT / 'tools/generate-app-catalog.py'


def read_manifest(path):
    rows = []
    for line in path.read_text(encoding='utf-8').splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        columns = line.split('\t')
        if len(columns) != 9:
            raise SystemExit(f'{path}: expected 9 columns, found {len(columns)}: {line!r}')
        rows.append(dict(zip(
            ('repo', 'bundle', 'ident', 'name', 'icon', 'categories', 'size', 'sha256', 'first_run'),
            columns)))
    return rows


def catalog_digest(catalog):
    digest = hashlib.sha256()
    for entry in sorted(catalog.glob('*.desktop')):
        digest.update(entry.name.encode())
        digest.update(entry.read_bytes())
    return digest.hexdigest()


def field(text, key):
    for line in text.splitlines():
        if line.startswith(key + '='):
            return line[len(key) + 1:]
    return None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('output', type=Path)
    parser.add_argument('--manifest', type=Path, default=DEFAULT_MANIFEST)
    args = parser.parse_args()
    output = args.output.resolve()
    catalog = output / 'lib/apps'
    rows = read_manifest(args.manifest)
    failures = []

    def check(condition, message):
        if not condition:
            failures.append(message)

    present = [row for row in rows if (output / row['bundle'].lstrip('/')).exists()]
    absent = [row for row in rows if row not in present]
    check(present, 'no manifest row has a bundle in the output root; nothing to verify')

    for row in present:
        entry = catalog / (row['ident'] + '.desktop')
        if not entry.exists():
            failures.append(f'{row["ident"]}: bundle present but no catalog entry')
            continue
        text = entry.read_text(encoding='utf-8')
        check(field(text, 'Exec') == row['bundle'],
              f'{row["ident"]}: Exec is {field(text, "Exec")!r}, expected {row["bundle"]!r}')
        check(field(text, 'TryExec') == row['bundle'],
              f'{row["ident"]}: TryExec is {field(text, "TryExec")!r}, expected {row["bundle"]!r}')

    for row in absent:
        entry = catalog / (row['ident'] + '.desktop')
        check(not entry.exists(),
              f'{row["ident"]}: bundle absent from the output root but an entry was written')

    # A missing-bundle row must emit nothing, proven with a row that cannot exist.
    probe = output / 'lib/preinstall-probe.list'
    probe.write_text(
        'taijios\t/dis/wm/__absent_probe__.zx\torg.taijiosnet.wm-__absent_probe__\tProbe\tsystem\tSystem\t\t\tlazy\n',
        encoding='utf-8')
    subprocess.run([sys.executable, str(GENERATOR), '--preinstall', str(probe), '--output-root', str(output)],
                   check=True, stdout=subprocess.DEVNULL)
    check(not (catalog / 'org.taijiosnet.wm-__absent_probe__.desktop').exists(),
          'a row naming a missing bundle emitted an entry')
    probe.unlink()

    before = catalog_digest(catalog)
    subprocess.run([sys.executable, str(GENERATOR), '--preinstall', str(args.manifest), '--output-root', str(output)],
                   check=True, stdout=subprocess.DEVNULL)
    after = catalog_digest(catalog)
    check(before == after, 'a second --preinstall run changed the catalog bytes')

    if failures:
        for failure in failures:
            print(f'FAIL {failure}')
        print(f'catalog_preinstall_test: {len(failures)} failure(s)')
        return 1
    print(f'catalog_preinstall_test: {len(present)} of {len(rows)} rows emitted, ids stable, second run identical')
    return 0


if __name__ == '__main__':
    sys.exit(main())
